# ВСЕ пользовательские настройки находятся ТОЛЬКО в этом файле
# (backup_config.py). Проверка корректности (валидация) — в config.py,
# его редактировать не нужно.
#
# Файл должен принадлежать root и быть доступен только root (здесь
# хранится пароль GPG):
#     chown root:root backup_config.py
#     chmod 600 backup_config.py
#
# Пароль из этого файла НИКОГДА не записывается в лог, не выводится
# при диагностике и не передается в аргументах командной строки
# внешним процессам (используется --passphrase-fd).


# ============================================
# SUBVOLUMES
# ============================================
# Резервируемые Btrfs subvolume. Поддерживаются две формы записи:
#   обычные пути:      SUBVOLUMES = ["/", "/home"]
#   словари (v1.0 v3): SUBVOLUMES = [{"name": "root", "source": "/"}]
# Имя subvolume выводится из пути, если не задано явно.

SUBVOLUMES = [
    "/",
    # "/home",
    # "/var",
]

# Каталог локальных Btrfs snapshots
SNAPSHOT_DIR = "/.snapshots"

# Каталог локальных резервных копий (архивов).
# None — используется SNAPSHOT_DIR/backup.
LOCAL_BACKUP_DIR = None


# ============================================
# COMPRESSION
# ============================================

# Основной метод сжатия: "zstd" или "gzip".
# ВНИМАНИЕ (скорость): zstd на 3-5 раз быстрее gzip при лучшей степени
# сжатия. Если резервное копирование кажется медленным — используйте
# zstd (пакет zstd) и уровень 1-3. Фактическое время каждого этапа
# печатается в ходе операции и пишется в журнал.
COMPRESSION = "zstd"

# Резервный метод сжатия (fallback)
COMPRESSION_FALLBACK = "gzip"

# Разрешить автоматический fallback в cron (без вопросов):
# True  — использовать COMPRESSION_FALLBACK, если основного нет;
# False — завершать операцию с ошибкой.
CRON_COMPRESSION_FALLBACK = True

# Уровни сжатия:
#   gzip: 1 (быстро, сжатие хуже) ... 9 (медленно, сжатие лучше);
#   zstd: 1 ... 19 (для бэкапов разумно 1-3).
# Уровень 6 gzip может сжимать 5 ГиБ заметно дольше, чем zstd -3.
GZIP_LEVEL = 6
ZSTD_LEVEL = 3


# ============================================
# GPG ENCRYPTION
# ============================================

GPG_BINARY = "/usr/bin/gpg"

# Пароль симметричного шифрования (AES256).
# Для cron должен быть задан реально; "CHANGE_ME" — значение-заполнитель.
# Если в интерактивном режиме задать другой пароль вручную (не из этого
# файла), он будет использован ТОЛЬКО для текущей операции — архивы,
# созданные с ним, проверяются/восстанавливаются именно с этим паролем.
GPG_PASSWORD = "CHANGE_ME"


# ============================================
# NETWORK STORAGE (необязательное)
# ============================================

# Использовать сетевое хранилище, если оно доступно.
# False — сетевые проверки и отправка не выполняются вовсе.
NETWORK_ENABLED = True

# Точка монтирования сетевой шары
NETWORK_MOUNT = "/mnt/backup"

# Каталог внутри сетевой шары
NETWORK_DIRECTORY = "btrfs-backup"

# Автоматическая сетевая отправка после успешного локального backup.
# False — архивы остаются локально со статусом upload-pending
# и отправляются командой upload-pending.
AUTO_UPLOAD = True

# Проверять наличие активного монтирования при обычном backup.
# ВНИМАНИЕ: эта настройка НЕ отключает обязательные проверки перед
# удалением данных (retention, финализация сетевой копии, upload-pending) —
# там монтирование проверяется всегда.
CHECK_NETWORK_MOUNT = True

# Ожидаемый тип файловой системы сетевой шары ("nfs", "cifs", "sshfs", ...).
# None — не проверять тип файловой системы.
EXPECTED_NETWORK_FS_TYPE = None

# Минимальный объем свободного места на сетевой шаре в байтах.
# 0 — не проверять.
MIN_NETWORK_FREE_BYTES = 0


# ============================================
# RETENTION
# ============================================

# Количество успешно сохраненных резервных копий на каждый subvolume
# (независимая история для каждого).
RETENTION_COUNT = 5


# ============================================
# TIMEOUTS
# ============================================

# Таймаут конвейеров (btrfs send | сжатие | gpg) в секундах.
# Для больших subvolume на медленном железе увеличьте (например 14400).
PROCESS_TIMEOUT = 3600


# ============================================
# LOGGING
# ============================================

LOG_FILE = "/var/log/btrfs-backup.log"
